import time
from engine import *
Q=["хочу к тёплому морю в ноябре, недорого, с ребёнком, без долгих перелётов","в декабре на 10 ночей вдвоём до 200 тыс",
   "дёшево, но люкс, в марте","с собакой в мае, бюджет 120 тыс","один на выходные, тепло","две недели в январе с 2 детьми до 300 тыс",
   "куда-нибудь где не жарко в августе","хочу море","в феврале на неделю с завтраком","сентябрь, 5 ночей, до 80 тыс"]
done=0;iss=0;t0=time.time();fixed=0
for q in Q:
    s=parse(q); top=rank(s)
    if not top: print("НЕТ ВАРИАНТОВ:",q); continue
    p=packages(s,dest_by_name(top[0]["name"]))["calm"]; n=len(p["issues"]); iss+=n
    for i in list(p["issues"]): apply_fix(s,p,dest_by_name(top[0]["name"]),i["code"])
    fixed+= n-len(p["issues"]) if n else 0; done+=1
print(f"сценариев доведено: {done}/{len(Q)}; конфликтов поймано: {iss}; исправлено фиксами: {fixed}; время/запрос: {(time.time()-t0)/len(Q)*1000:.0f} мс; уточняющих вопросов: 0")
